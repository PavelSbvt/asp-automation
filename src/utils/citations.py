def get_citation_with_author() -> tuple[str, str]:
    """
    Возвращает случайную цитату и её автора вместе

    :return: tuple[str, str] - возвращает кортеж из текста цитаты и её автора
    """

    citation = random.choice(list(QUOTES))
    author = QUOTES[citation]
    Rich.print_spacer_points()
    Rich.debug_log(f"Цитата: {citation}")
    Rich.debug_log(f"Автор цитаты: {author}")

    return citation, author
